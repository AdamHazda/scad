export function localizeGroupName(groupName: string, lang: Language): string {
  if (!groupName) return TRANSLATIONS[lang]?.mainParams || 'Parameters';
  const cleanKey = groupName.trim().toLowerCase();
  const found = GROUP_DICTIONARY[cleanKey];
  if (found && found[lang]) {
    return found[lang];
  }
  return groupName;
}

export function localizeParamName(name: string, key: string, lang: Language): string {
  const normKey = (key || '').toLowerCase().trim();
  const normName = (name || '').toLowerCase().trim();

  // Try direct dictionary matching by key or name
  if (PARAM_DICTIONARY[normKey]?.[lang]) {
    return PARAM_DICTIONARY[normKey][lang];
  }
  if (PARAM_DICTIONARY[normName]?.[lang]) {
    return PARAM_DICTIONARY[normName][lang];
  }

  // Fallback: format snake_case or camelCase into clean readable title
  const readable = (name || key)
    .replace(/_/g, ' ')
    .replace(/([a-z])([A-Z])/g, '$1 $2')
    .replace(/\b\w/g, (c) => c.toUpperCase());

  return readable;
}

